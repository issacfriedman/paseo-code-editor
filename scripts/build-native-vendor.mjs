// Builds client/native/vendor/lezer.js: the lezer grammars as one file with classes compiled away.
import { build } from "esbuild";
import { transformAsync } from "@babel/core";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const result = await build({
  entryPoints: [`${root}/vendor-src/lezer-native.ts`],
  bundle: true,
  format: "esm",
  target: "es2020",
  write: false,
  legalComments: "none",
});
const out = await transformAsync(result.outputFiles[0].text, {
  babelrc: false,
  configFile: false,
  compact: false,
  plugins: [
    "@babel/plugin-transform-class-static-block",
    "@babel/plugin-transform-private-methods",
    "@babel/plugin-transform-class-properties",
    "@babel/plugin-transform-classes",
  ],
});
writeFileSync(
  `${root}/client/native/vendor/lezer.js`,
  "// Generated by scripts/build-native-vendor.mjs. Do not edit.\n" + out.code,
);
console.log("wrote client/native/vendor/lezer.js", out.code.length, "chars");
